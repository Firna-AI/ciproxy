/** Regenerate the Rust-owned HTTP contract and compare it in gate mode. */
import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../../", import.meta.url));
const directory = new URL("./generated/", import.meta.url);
const scratch = new URL(
  "../../.context/ciproxy-mvp-m14/generated/",
  import.meta.url,
);
const check = process.argv.includes("--check");
const built = spawnSync(
  "cargo",
  ["run", "--quiet", "--package", "ciproxy-api", "--bin", "ciproxy-openapi"],
  { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
);
if (built.error) throw built.error;
if (built.status !== 0) {
  process.stderr.write(built.stderr);
  process.exit(built.status ?? 1);
}
await mkdir(scratch, { recursive: true });
const document = new URL("openapi.json", scratch);
await writeFile(document, `${built.stdout}\n`);
const types = `/**\n * Generated by openapi-typescript from ciproxy-api Rust types.\n * Do not edit this file by hand.\n */\n\n${astToString(await openapiTS(document))}`;
const files = [
  ["openapi.json", `${built.stdout}\n`],
  ["api.d.ts", types],
] as const;
await mkdir(directory, { recursive: true });
let drift = false;
for (const [name, content] of files) {
  const path = new URL(name, directory);
  if (check) {
    const saved = await readFile(path, "utf8").catch((error: unknown) => {
      if (error instanceof Error && "code" in error && error.code === "ENOENT")
        return "";
      throw error;
    });
    if (saved !== content) {
      drift = true;
      process.stderr.write(
        `Generated API contract differs: ts/api/generated/${name}\n`,
      );
    }
  } else {
    await writeFile(path, content);
  }
}
if (drift) process.exitCode = 1;
