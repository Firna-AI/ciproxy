//! Generated HTTP reference from the same registration that builds the router.

use utoipa::openapi::header::Header;
use utoipa::openapi::response::Response;
use utoipa::openapi::security::{ApiKey, ApiKeyValue, SecurityRequirement, SecurityScheme};
use utoipa::openapi::{Content, Info, OpenApi, Ref, RefOr, Server};
use utoipa::{IntoParams, PartialSchema, ToSchema};

use crate::error::Problem;
use crate::router;
use crate::wire::access::MutationHeaders;

/// Return complete Rust-owned schemas, authorization, responses, and headers.
pub fn document() -> OpenApi {
    let (_, mut document) = router::routes().split_for_parts();
    document.info = Info::new("ciproxy dashboard API", env!("CARGO_PKG_VERSION"));
    document.info.description =
        Some("Generated by utoipa from ciproxy-api Rust routes and serde types.".to_owned());
    document.servers = Some(vec![Server::new("/api")]);
    let components = document.components.get_or_insert_default();
    components
        .schemas
        .insert(Problem::name().into_owned(), Problem::schema());
    let mut nested = Vec::new();
    Problem::schemas(&mut nested);
    components.schemas.extend(nested);
    components.add_security_scheme(
        "session",
        SecurityScheme::ApiKey(ApiKey::Cookie(ApiKeyValue::new("__Host-ciproxy"))),
    );
    components.add_security_scheme(
        "csrf",
        SecurityScheme::ApiKey(ApiKey::Header(ApiKeyValue::new("x-ciproxy-csrf"))),
    );
    for path in document.paths.paths.values_mut() {
        for (mutating, operation) in [
            (false, &mut path.get),
            (true, &mut path.put),
            (true, &mut path.post),
            (true, &mut path.delete),
            (false, &mut path.head),
        ] {
            let Some(operation) = operation else {
                continue;
            };
            if mutating && operation.security.is_some() {
                operation.security = Some(vec![
                    SecurityRequirement::new("session", Vec::<String>::new())
                        .add("csrf", Vec::<String>::new()),
                ]);
                operation.parameters.get_or_insert_default().extend(
                    MutationHeaders::into_params(|| None)
                        .into_iter()
                        .map(RefOr::T),
                );
            }
            for (status, description) in [
                ("400", "Malformed request"),
                ("401", "Sign-in absent, expired, or revoked"),
                ("403", "Workspace role, origin, or CSRF token refused"),
                ("404", "Resource absent in this workspace"),
                ("405", "Method not allowed"),
                ("409", "Conflicting resource state"),
                ("413", "Request body is too large"),
                ("415", "Unsupported content type"),
                ("422", "GitHub label refusal or malformed body"),
                ("500", "Internal operation failed"),
                ("503", "Temporary upstream or agent failure"),
            ] {
                let mut response = Response::new(description);
                response.content.insert(
                    "application/json".to_owned(),
                    Content::new(Some(Ref::from_schema_name(Problem::name().into_owned()))).into(),
                );
                operation
                    .responses
                    .responses
                    .insert(status.to_owned(), response.into());
            }
            for response in operation.responses.responses.values_mut() {
                if let RefOr::T(response) = response {
                    response
                        .headers
                        .insert("x-ciproxy-build".to_owned(), Header::default().into());
                    if response.description.contains("redirect") {
                        response
                            .headers
                            .insert("Location".to_owned(), Header::default().into());
                        response
                            .headers
                            .insert("Set-Cookie".to_owned(), Header::default().into());
                    }
                }
            }
        }
    }
    document
}
